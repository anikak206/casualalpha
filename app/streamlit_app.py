"""CausalAlpha Streamlit dashboard (Phase 6)."""

import os
from pathlib import Path

import pandas as pd
import streamlit as st

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"


def _img(name):
    p = RESULTS / name
    if p.exists():
        st.image(str(p))
    else:
        st.warning(f"Missing {name}")


st.set_page_config(page_title="CausalAlpha", layout="wide")
st.title("CausalAlpha - which futures lead-lag relationships survive OOS?")

st.sidebar.header("Options")
window = None
gt_path = RESULTS / "granger_tests.csv"
if gt_path.exists():
    gt = pd.read_csv(gt_path)
    windows = sorted(gt["window_start"].unique())
    window = st.sidebar.selectbox("Causal graph window (start)", windows)

# Causal graph at chosen date
st.header("Causal graph (significant edges, BH) at selected window")
if window is not None:
    sub = gt[(gt["window_start"] == window) & (gt["significant_bh"])]
    edges = sub[["leader", "follower", "lag", "p_value_bh"]].sort_values("p_value_bh")
    st.dataframe(edges, use_container_width=True)
    st.caption(f"{edges[['leader','follower']].drop_duplicates().shape[0]} directed edges significant in this window.")

st.header("Edge stability heatmap")
_img("edge_stability_heatmap.png")

st.header("Regime timeline")
_img("regime_timeline.png")

st.header("Regime x edge stability")
_img("regime_edge_heatmap.png")

st.header("Equity curves vs baselines")
_img("equity_curves.png")

st.header("Strategy comparison")
comp_path = RESULTS / "strategy_comparison.csv"
if comp_path.exists():
    comp = pd.read_csv(comp_path, index_col=0)
    st.dataframe(comp, use_container_width=True)

st.header("Validation summary")
vs_path = RESULTS / "validation_summary.csv"
if vs_path.exists():
    st.dataframe(pd.read_csv(vs_path), use_container_width=True)

st.header("Honest verdict")
verdict_path = RESULTS / "verdict.txt"
if verdict_path.exists():
    st.text(verdict_path.read_text())

st.header("Sentiment status")
ss_path = RESULTS / "sentiment_status.txt"
if ss_path.exists():
    st.text(ss_path.read_text())

st.caption("All numbers generated by code in results/. No hype: negative results reported as-is.")
